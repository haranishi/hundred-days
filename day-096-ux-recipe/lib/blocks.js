export function makeBlock(goal, type, id) {
  const sample = RECIPES[goal]?.blocks?.find(block => block.type === type);
  return { id, type, variant: sample?.variant ?? 0, props: structuredClone(sample?.props ?? GENERIC[type]) };
}
