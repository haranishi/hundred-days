export function buildFromRecipe(goal) {
  const recipe = RECIPES[goal];
  return {
    v: SCHEMA_VERSION, goal, site: { name: recipe.siteName }, theme: { ...recipe.theme },
    blocks: recipe.blocks.map((sample, index) => ({ id: `b${index + 1}`, ...structuredClone(sample) })),
  };
}

