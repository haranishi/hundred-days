export function assessEvidence(caseData,person,evidenceId){
  const story=STORIES[caseData.id];
  if(!story?.evidence.some(e=>e.id===evidenceId))return {status:'invalid'};
  const answer=investigate(caseData,person);
  if(!answer.contradiction)return {status:'supported',...answer};
  if(evidenceId!==story.key)return {status:'irrelevant',...answer};
  return {status:'contradiction',...answer};
}
